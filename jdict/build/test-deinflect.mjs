let fail = 0;
for (const [input, base, type] of CASES) {
  const hit = deinflect(input).find((c) => c.word === base && (c.type & type));
  if (!hit) { fail++; console.log('✗', input, '→', base); }
  else console.log('✓', input, '→', base, '(' + hit.reasons.join(' → ') + ')');
}
console.log(`\n${CASES.length - fail}/${CASES.length} 通過`);
process.exit(fail ? 1 : 0);
